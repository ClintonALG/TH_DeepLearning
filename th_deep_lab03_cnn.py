# 1. Nạp dữ liệu MNIST (Chữ số)
(X_train, y_train), (X_test, y_test) = tf.keras.datasets.mnist.load_data()

# 2. Tiền xử lý: Chuẩn hóa pixel về [0, 1] và reshape sang 4D
X_train = X_train.reshape(-1, 28, 28, 1).astype('float32') / 255.0
X_test = X_test.reshape(-1, 28, 28, 1).astype('float32') / 255.0

# 3. Xây dựng mô hình CNN
model1 = Sequential([
    Input(shape=(28, 28, 1)),
    Conv2D(32, kernel_size=(3, 3), activation='relu'), # Tầng chập 1
    MaxPool2D(pool_size=(2, 2)),                       # Tầng gộp 1
    Conv2D(64, kernel_size=(3, 3), activation='relu'),
    MaxPool2D(pool_size=(2, 2)),
    Flatten(),                                         # Duỗi ảnh thành vector
    Dense(128, activation='relu'),
    Dense(10, activation='softmax')                    # 10 nhãn đầu ra
])

model1.compile(optimizer='adam', loss='sparse_categorical_crossentropy', metrics=['accuracy'])
model1.fit(X_train, y_train, epochs=5, batch_size=64)
model1.save('mnist_model.h5')

