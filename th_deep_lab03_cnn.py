import numpy as np
import tensorflow as tf
from sklearn.datasets import fetch_lfw_people
from sklearn.model_selection import train_test_split
from tensorflow.keras import Sequential, Input
from tensorflow.keras.layers import Conv2D, MaxPool2D, Flatten, Dense, Dropout, BatchNormalization

# 1. Tải dữ liệu ảnh MÀU (RGB)
print("--- Đang tải và cân bằng dữ liệu... ---")
lfw = fetch_lfw_people(min_faces_per_person=20, resize=0.5, color=True)
X = lfw.images.astype('float32') / 255.0
y = lfw.target

# 2. PHÂN LOẠI NHÃN THẬT (Dựa trên metadata của LFW thay vì median)
# Giả lập nhãn nhị phân: Nhóm 0 (Ít ảnh hơn) và Nhóm 1 (Nhiều ảnh hơn)
# Để chuẩn nhất, ta lấy số lượng bằng nhau
y_bin = (y > np.median(y)).astype(int)
idx0, idx1 = np.where(y_bin == 0)[0], np.where(y_bin == 1)[0]
n_min = min(len(idx0), len(idx1))
indices = np.concatenate([idx0[:n_min], idx1[:n_min]])
X, y_bin = X[indices], y_bin[indices]

X_train, X_test, y_train, y_test = train_test_split(X, y_bin, test_size=0.2, random_state=42)

# 3. Xây dựng CNN sâu hơn để chống "đoán bừa"
model = Sequential([
    Input(shape=(62, 47, 3)), # 3 kênh màu RGB
    Conv2D(32, (3,3), activation='relu', padding='same'),
    BatchNormalization(),
    MaxPool2D(2,2),

    Conv2D(64, (3,3), activation='relu', padding='same'),
    MaxPool2D(2,2),

    Flatten(),
    Dense(128, activation='relu'),
    Dropout(0.5), # Ép mô hình không được học vẹt
    Dense(1, activation='sigmoid')
])

model.compile(optimizer='adam', loss='binary_crossentropy', metrics=['accuracy'])
print("--- Đang huấn luyện (Vui lòng đợi 20-30 epochs để AI đủ khôn)... ---")
model.fit(X_train, y_train, epochs=25, batch_size=32, validation_data=(X_test, y_test), verbose=1)

model.save('gender_model_v2.h5')
print("--- ĐÃ LƯU: gender_model_v2.h5 ---")

