class TrapezoidParallelProof(tf.Module):
    @tf.function
    def __call__(self, AD, BC, AB, CD):
        cond1 = tf.equal(AD, BC)
        cond2 = tf.equal(AB, CD)
        # Trả về True nếu cả 2 điều kiện đều đúng
        return tf.logical_and(cond1, cond2)

model_17 = TrapezoidParallelProof()
print("Bài 17:", model_17(tf.constant(5), tf.constant(5), tf.constant(10), tf.constant(10)).numpy())

