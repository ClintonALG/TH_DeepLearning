class TrapezoidBaseProof(tf.Module):
    @tf.function
    def __call__(self, AD, BC, is_parallel):
        cond1 = tf.equal(AD, BC)
        return tf.logical_and(cond1, is_parallel)

model_18 = TrapezoidBaseProof()
print("Bài 18:", model_18(tf.constant(4), tf.constant(4), tf.constant(True)).numpy())

