class TriangleMidsegmentProof(tf.Module):
    @tf.function
    def __call__(self, AM, MB, MN, BC):
        # Đường trung bình cần thỏa mãn MN = BC/2
        cond1 = tf.equal(AM, MB)
        cond2 = tf.equal(MN, BC / 2.0)

        return tf.logical_and(cond1, cond2)

model_19 = TriangleMidsegmentProof()
print("Bài 19:", model_19(tf.constant(3.0), tf.constant(3.0), tf.constant(5.0), tf.constant(10.0)).numpy())