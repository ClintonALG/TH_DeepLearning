class BoxSurfaceArea(tf.Module):
    @tf.function
    def __call__(self, a, b, c):
        s_xq = (a + b) * c * 2
        s_tp = (a * b) * 2 + s_xq
        return s_tp

model_16 = BoxSurfaceArea()
print("Bài 16 (a=2, b=3, c=4):", model_16(tf.constant(2), tf.constant(3), tf.constant(4)).numpy())

